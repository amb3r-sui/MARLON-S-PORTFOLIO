import type { DemoOutcome, WorkflowExplorerDefinition, WorkflowExplorerEdge, WorkflowExplorerNode, WorkflowNodeKind } from "@/types";

const node = (
  id: string,
  label: string,
  kind: WorkflowNodeKind,
  x: number,
  y: number,
  subtitle: string,
  details: string,
): WorkflowExplorerNode => ({ id, label, kind, x, y, subtitle, details });

const edge = (from: string, to: string, label?: string, dashed = false): WorkflowExplorerEdge =>
  ({ from, to, ...(label ? { label } : {}), ...(dashed ? { dashed } : {}) });

const paths = (
  success: string[],
  validationError: string[],
  duplicate: string[],
  providerFailure: string[],
  rateLimited: string[] = providerFailure,
): Partial<Record<DemoOutcome, string[]>> => ({
  success,
  "validation-error": validationError,
  duplicate,
  "provider-failure": providerFailure,
  "rate-limited": rateLimited,
});

